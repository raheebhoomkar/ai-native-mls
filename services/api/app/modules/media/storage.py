"""Where media bytes live. Everything else talks to the `Storage` interface, so local disk
(development, tests) and S3-compatible object storage (production) are interchangeable.

Keys are generated by the media service (`<organisation>/<asset>`), never taken from users.
"""

from functools import lru_cache
from pathlib import Path
from typing import Any, Protocol

from app.core.config import get_settings


class Storage(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...

    def get(self, key: str) -> bytes:
        """Raise FileNotFoundError when the key does not exist."""
        ...

    def delete(self, key: str) -> None:
        """Do nothing when the key does not exist."""
        ...


class LocalStorage:
    """Files under one directory. Not shared between machines: use it for one server only."""

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root) or path == self.root:
            raise ValueError("Invalid storage key.")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write then rename, so a reader never sees half a file.
        partial = path.with_name(path.name + ".partial")
        partial.write_bytes(data)
        partial.replace(path)

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3Storage:
    """Any S3-compatible bucket. The bucket should be private; files are served by the API."""

    def __init__(self, bucket: str, client: Any) -> None:
        self.bucket = bucket
        self.client = client

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self.client.put_object(Bucket=self.bucket, Key=key, Body=data, ContentType=content_type)

    def get(self, key: str) -> bytes:
        try:
            response = self.client.get_object(Bucket=self.bucket, Key=key)
        except self.client.exceptions.NoSuchKey:
            raise FileNotFoundError(key) from None
        body: bytes = response["Body"].read()
        return body

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=key)  # no error if missing


@lru_cache
def get_storage() -> Storage:
    settings = get_settings()
    if settings.media_storage == "s3":
        import boto3  # type: ignore[import-untyped]  # only needed with S3

        client = boto3.client(
            "s3",
            endpoint_url=settings.media_s3_endpoint_url,
            region_name=settings.media_s3_region,
        )
        return S3Storage(settings.media_s3_bucket or "", client)
    return LocalStorage(settings.media_root)
